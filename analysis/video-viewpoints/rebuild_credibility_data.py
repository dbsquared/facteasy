def apply_fix(text, pairs):
    for old, new in pairs:
        if old and old in text:
            text = text.replace(old, new)
    return text


def mark_key(segments, patterns):
    for seg in segments:
        seg['key'] = any(p in seg['text'] for p in patterns)
    return segments


def main():
    with open(SRC, 'r', encoding='utf-8') as f:
        data = json.load(f)

    items = data['items']
    done = 0
    for it in items:
        iid = it['id']
        spec = AUTHORED.get(iid)
        if not spec:
            print('[WARN] #%d 无新数据，跳过' % iid)
            continue

        it['natures'] = spec['natures']
        it['nature_basis'] = spec['nature_basis']
        it['sources'] = spec['sources']
        it['holds'] = spec['holds']
        it['doubts'] = spec['doubts']
        it.pop('nature', None)
        it.pop('nature_reason', None)
        it.pop('key_sources', None)

        for extra in ('rating', 'sub_ratings', 'note', 'timeliness', 'scope',
                      'reliability', 'evidence_strength'):
            if extra in spec:
                it[extra] = spec[extra]

        # 原文：关键句标注 + 勘误
        quote = it.get('quote') or {}
        segs = quote.get('segments') or []
        mark_key(segs, spec.get('key', []))
        for seg in segs:
            fixed = apply_fix(seg['text'], spec.get('fix', []))
            if fixed != seg['text']:
                seg['fix'] = fixed
        quote['segments'] = segs
        quote['stats'] = {
            'lines': len(segs),
            'chars': sum(len(s['text']) for s in segs),
            'key_lines': sum(1 for s in segs if s.get('key')),
            'fix_lines': sum(1 for s in segs if s.get('fix')),
        }
        quote['note'] = ('逐字稿由 Whisper（faster-whisper-medium）自动转写，存在同音讹误；'
                         '括号内为按语义与史实补正的勘误，仅关键句逐条标注。')
        it['quote'] = quote
        done += 1

    data['nature_definitions'] = NATURE_DEF
    data['nature_legend_note'] = TAG_LEGEND_NOTE
    data['assessment']['method'] = ('来源性质标签法（转述 / 专属 / 原创，可多标签并存）+ '
                                    '权威层级 T0-T4 + 逐条出处与根据 + 综合评级 A/B/C/D/N-A')
    data['assessment']['date'] = '2026-09-03'

    counts = {}
    for it in items:
        counts[it['rating']] = counts.get(it['rating'], 0) + 1
    data['assessment']['counts'] = counts

    with open(SRC, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write('\n')

    print('已重建 %s' % SRC)
    print('  观点条目：%d 条（已处理 %d 条）' % (len(items), done))
    print('  原文行：%d 行；关键句：%d 行；勘误：%d 行'
          % (sum(i['quote']['stats']['lines'] for i in items),
             sum(i['quote']['stats']['key_lines'] for i in items),
             sum(i['quote']['stats']['fix_lines'] for i in items)))
    print('  来源条目：%d 条' % sum(len(i.get('sources') or []) for i in items))
    return 0


